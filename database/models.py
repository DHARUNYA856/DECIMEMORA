from datetime import datetime, timezone
from flask_login import UserMixin
from werkzeug.security import generate_password_hash,check_password_hash
from database.db import db

def now():return datetime.now(timezone.utc)
class User(UserMixin,db.Model):
 id=db.Column(db.Integer,primary_key=True)
 employee_id=db.Column(db.String(40),unique=True,nullable=False)
 name=db.Column(db.String(120),nullable=False)
 username=db.Column(db.String(80),unique=True,nullable=False)
 password_hash=db.Column(db.String(255),nullable=False)
 email=db.Column(db.String(160),unique=True,nullable=False)
 department=db.Column(db.String(100),default='General')
 role=db.Column(db.String(40),default='New Employee')
 status=db.Column(db.String(20),default='active')
 created_at=db.Column(db.DateTime,default=now)
 created_by=db.Column(db.Integer,db.ForeignKey('user.id'))
 last_login=db.Column(db.DateTime)
 def set_password(self,p):self.password_hash=generate_password_hash(p)
 def check_password(self,p):return check_password_hash(self.password_hash,p)
 @property
 def is_active(self):return self.status=='active'
class Project(db.Model):
 id=db.Column(db.Integer,primary_key=True)
 project_code=db.Column(db.String(50),unique=True,nullable=False)
 project_name=db.Column(db.String(150),nullable=False)
 description=db.Column(db.Text,default='')
 department=db.Column(db.String(100),default='General')
 status=db.Column(db.String(20),default='active')
 created_by=db.Column(db.Integer,db.ForeignKey('user.id'))
 created_at=db.Column(db.DateTime,default=now)
class ProjectMember(db.Model):
 id=db.Column(db.Integer,primary_key=True)
 project_id=db.Column(db.Integer,db.ForeignKey('project.id'),nullable=False)
 user_id=db.Column(db.Integer,db.ForeignKey('user.id'),nullable=False)
 access_level=db.Column(db.String(30),default='read')
 assigned_by=db.Column(db.Integer,db.ForeignKey('user.id'))
 assigned_at=db.Column(db.DateTime,default=now)
 __table_args__=(db.UniqueConstraint('project_id','user_id'),)
class Document(db.Model):
 id=db.Column(db.Integer,primary_key=True)
 project_id=db.Column(db.Integer,db.ForeignKey('project.id'),nullable=False)
 uploaded_by=db.Column(db.Integer,db.ForeignKey('user.id'))
 file_name=db.Column(db.String(255),nullable=False)
 file_path=db.Column(db.String(500),nullable=False)
 file_type=db.Column(db.String(10))
 status=db.Column(db.String(30),default='pending')
 restricted=db.Column(db.Boolean,default=False)
 uploaded_at=db.Column(db.DateTime,default=now)
class PermissionRequest(db.Model):
 id=db.Column(db.Integer,primary_key=True)
 user_id=db.Column(db.Integer,db.ForeignKey('user.id'),nullable=False)
 project_id=db.Column(db.Integer,db.ForeignKey('project.id'),nullable=False)
 document_id=db.Column(db.Integer,db.ForeignKey('document.id'),nullable=False)
 request_type=db.Column(db.String(40),default='document_read')
 reason=db.Column(db.Text,default='')
 status=db.Column(db.String(20),default='pending')
 approved_by=db.Column(db.Integer,db.ForeignKey('user.id'))
 created_at=db.Column(db.DateTime,default=now)
 approved_at=db.Column(db.DateTime)
class Decision(db.Model):
 id=db.Column(db.Integer,primary_key=True)
 project_id=db.Column(db.Integer,db.ForeignKey('project.id'),nullable=False)
 problem=db.Column(db.Text,nullable=False)
 context=db.Column(db.Text,default='')
 options=db.Column(db.Text,default='')
 decision=db.Column(db.Text,nullable=False)
 reason=db.Column(db.Text,default='')
 action_taken=db.Column(db.Text,default='')
 outcome=db.Column(db.Text,default='')
 status=db.Column(db.String(30),default='open')
 created_by=db.Column(db.Integer,db.ForeignKey('user.id'))
 created_at=db.Column(db.DateTime,default=now)
class ChatHistory(db.Model):
 id=db.Column(db.Integer,primary_key=True)
 user_id=db.Column(db.Integer,db.ForeignKey('user.id'),nullable=False)
 project_id=db.Column(db.Integer,db.ForeignKey('project.id'),nullable=False)
 question=db.Column(db.Text,nullable=False)
 answer=db.Column(db.Text,nullable=False)
 created_at=db.Column(db.DateTime,default=now)
